#!/usr/bin/env python3
"""treg_prepare — the five Treg-paradigm animals through the afferent2p pipeline in three pastes (Nov 2026).

Run it in the Anaconda Prompt that you use for the pipeline (the Administrator one, so that it can
overwrite the files earlier runs wrote):

    cd D:\\2photon\\Chao\\GCAMP_affrerents
    python treg_prepare.py              # 1: plan + batch (default settings) + tuning plan for every animal
                                        #    -> paste treg_sweeps_A.m into one MATLAB, treg_sweeps_B.m into another
    python treg_prepare.py --after      # 2: after the sweeps: tuning report + apply (one common setting per FOV),
                                        #    batch with the tuned settings -> paste treg_aqua_all.m into MATLAB
    python treg_prepare.py --check      # 3: after MATLAB: what is done, the CFU overlap check, the status per animal

Every step is the same as the GUI's tabs 4 -> 3 -> 4 -> 5 (Run all, guided), only for all five animals in one go;
the GUI can take over at any point (its status strip reads the same files). Restartable: finished sweep jobs,
results and tuned settings are kept. The run labels (which run is which FOV, the second-injection day) are in
each animal's run_labels.csv, the day names in day_labels.csv.
"""
from __future__ import annotations
import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(r"D:\2photon\Chao\GCAMP_affrerents")
PIPE = ROOT / "afferent2p"
sys.path.insert(0, str(PIPE))

MICE = ["NavTIGRE-2609-1", "NavTIGRETreg-2609-1", "NavTIGRETreg-2609-2", "NavTIGRETreg-2608-1", "NavTIGRE-2608-1"]
GROUPS = {"A": ["NavTIGRE-2609-1", "NavTIGRETreg-2608-1", "NavTIGRE-2608-1"],      # two MATLAB instances, ~equal work
          "B": ["NavTIGRETreg-2609-1", "NavTIGRETreg-2609-2"]}
AQUA_DIR = r"H:\MATLAB\AQuA2"
UM_PER_PX, BORDER, SEC = 0.792, 5, 2.0
MAX_FALSE, MIN_FIBRE, TOL_RECALL = 0.10, 0.80, 0.05
N_INJECT = 72


def log(*a):
    print(*a, flush=True)


def mice(names):
    out = []
    for n in names:
        m = ROOT / n
        if m.is_dir():
            out.append(m)
        else:
            log(f"!! {m} not found — skipped")
    return out


def script_name(m: Path, kind: str) -> str:
    """The MATLAB script the manifest recorded (v40: a locked file is written under another name)."""
    if kind == "sweep":
        man = json.loads((m / "aqua_tune" / "tune_manifest.json").read_text(encoding="utf-8"))
        return str(m / "aqua_tune" / man.get("files", {}).get("script", "run_aqua_tune.m"))
    man = json.loads((m / "aqua_batch" / "manifest.json").read_text(encoding="utf-8"))
    return str(m / "aqua_batch" / man.get("files", {}).get("both_script", "run_aqua_and_cfu.m"))


def write_driver(path: Path, title: str, scripts: list[tuple[str, str]], done_msg: str):
    """scripts = [(mouse name, full path of the MATLAB script)]."""
    lines = [f"%% {path.name} — generated by treg_prepare.py: {title}",
             "% Each script is restartable (finished jobs / results are skipped); the parallel pool is",
             "% closed between animals so that every script attaches its own helper files.",
             "% The start time lives in the root appdata: the batch scripts clear the workspace.",
             "setappdata(0, 'treg_t0', tic);"]
    for mouse, s in scripts:
        lines += ["delete(gcp('nocreate'));",
                  f"fprintf('\\n===== %s  {mouse} =====\\n', datestr(now));",
                  f"run('{s}');"]
    lines += ["delete(gcp('nocreate'));",
              "if isappdata(0, 'treg_t0'), tElapsed = toc(getappdata(0, 'treg_t0')) / 3600; else, tElapsed = NaN; end",
              f"fprintf('\\n===== %s  all done in %.1f h — {done_msg} =====\\n', datestr(now), tElapsed);"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def batch(m: Path, opts_default: Path | None):
    import aqua_batch
    st: dict = {}
    out = aqua_batch.build_mouse(m, aqua_dir=AQUA_DIR, opts_default=opts_default, sec=SEC, um_per_px=UM_PER_PX,
                                 border=BORDER, overwrite=False, log=log, stats=st)
    if out is None:
        raise RuntimeError(f"{m.name}: no runs found")
    log(f"  batch: {st}")
    return st


def stage_prepare(names):
    import aqua_tune
    from afferent2p import tune as T
    from afferent2p.plan import plan_mouse, describe
    sweeps = {}
    for m in mice(names):
        log(f"\n################ {m.name}")
        log(describe(plan_mouse(m)))
        batch(m, PIPE / "default_Opt.csv")
        aqua_tune.plan(m, AQUA_DIR, dict(T.DEFAULT_GRID), None, False, UM_PER_PX, N_INJECT, True, True, None, 0,
                       days_filter=None, n_workers=0, amplitudes=list(T.AMPLITUDES), sizes=list(T.SIZES_PX),
                       per_condition="auto", log=log)
        sweeps[m.name] = script_name(m, "sweep")
        pr = aqua_tune.sweep_progress(m)
        log(f"  sweep: {pr['head']}")
    for g, members in GROUPS.items():
        scripts = [(n, sweeps[n]) for n in members if n in sweeps]
        if scripts:
            p = ROOT / f"treg_sweeps_{g}.m"
            write_driver(p, f"tuning sweeps of {', '.join(members)}", scripts,
                         "now: python treg_prepare.py --after")
            log(f"\nMATLAB instance {g}:  run('{p}')")
    log("\nPaste treg_sweeps_A.m into one interactive MATLAB and treg_sweeps_B.m into another (the user-level MATLAB sees H:).\n"
        "When both say 'all done': python treg_prepare.py --after")


def stage_after(names):
    import aqua_tune
    scripts = []
    for m in mice(names):
        log(f"\n################ {m.name}")
        pr = aqua_tune.sweep_progress(m)
        log(f"  sweep: {pr['head']}")
        if pr["done"] == 0:
            log("  !! no sweep job finished — skipped (run the sweep first)"); continue
        if pr["pending"] or pr["failed"]:
            log(f"  WARNING: {pr['pending']} job(s) pending and {pr['failed']} failed — scoring what finished")
        res = aqua_tune.report(m, MAX_FALSE, MIN_FIBRE, None, True, apply_all=True, apply_common=True,
                               day_rule="matched", tol_recall=TOL_RECALL, log=log)
        if res.get("rule_not_met"):
            log(f"  NOTE: rule not met for {', '.join(res['rule_not_met'])} — the best trade-off was written")
        if res.get("grid_suggest"):
            log(f"  NOTE: the report suggests a wider grid: {res['grid_suggest']} (tab 3 'Extend the grid' when wanted)")
        if not res.get("written"):
            log("  !! the report applied no setting — skipped"); continue
        batch(m, PIPE / "default_Opt.csv")
        scripts.append((m.name, script_name(m, "both")))
    if scripts:
        p = ROOT / "treg_aqua_all.m"
        write_driver(p, "AQuA2 + CFU batches of the Treg animals", scripts, "now: python treg_prepare.py --check")
        log(f"\nMATLAB:  run('{p}')     (one instance is enough; ~1 min per movie + the CFU step)")


def stage_check(names):
    import aqua_batch
    from afferent2p import cfu_overlap as C
    from afferent2p.pipeline_state import mouse_state, format_state
    for m in mice(names):
        log(f"\n################ {m.name}")
        bd = aqua_batch.batch_done(m)
        log(f"  MATLAB: {bd['text']}")
        if bd["done"]:
            try:
                C.check_mouse(m, log=log)
            except Exception as e:
                log(f"  overlap check failed: {e}")
        try:
            log(format_state(mouse_state(m, SEC)))
        except Exception as e:
            log(f"  status failed: {e}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--after", action="store_true", help="stage 2: report + apply + batch with the tuned settings")
    ap.add_argument("--check", action="store_true", help="stage 3: what MATLAB produced, overlap check, status")
    ap.add_argument("--mice", nargs="*", default=None, help="only these animals (default: all five)")
    a = ap.parse_args()
    names = a.mice or MICE
    t0 = time.time()
    if a.after:
        stage_after(names)
    elif a.check:
        stage_check(names)
    else:
        stage_prepare(names)
    log(f"\n({(time.time() - t0) / 60:.1f} min)")


if __name__ == "__main__":
    main()
