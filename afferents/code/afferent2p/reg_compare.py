def _link_or_copy(src: Path, dst: Path):
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def _preset_for(mouse_dir: Path, run_entry: dict, opts_default: Path | None, log=print) -> tuple[dict, str]:
    """The AQuA2 settings the main batch used for this run (manifest presets), else a settings file, else the default."""
    man = mouse_dir / "aqua_batch" / "manifest.json"
    if man.exists() and run_entry.get("preset"):
        m = json.loads(man.read_text())
        for p in m.get("presets", []):
            if int(p["preset"]) == int(run_entry["preset"]):
                return dict(p["values"]), f"Preset{p['preset']} of aqua_batch\\manifest.json ({p.get('source', '')})"
    cand = [mouse_dir / "aqua_opts" / f"{run_entry['experiment']}_Opt.csv"]
    cand += sorted(mouse_dir.glob("*_Opt.csv"))
    for c in cand:
        if c.exists():
            vals = read_opt_csv(c)
            return build_preset(vals, 2.0, None, None, log=log, warn=False), c.name
    dflt = opts_default or (HERE / "default_Opt.csv")
    return build_preset(read_opt_csv(dflt), 2.0, None, None, log=log, warn=False), f"{dflt.name} (no tuned settings found)"


def cmd_prepare(mouse_dir: Path, runs: list[str], aqua_dir: str, as_root: str | None, add_legacy: bool, bin_frames: int | None,
                cfu_min_events: int, cfu_overlap: float, overwrite: bool, opts_default: Path | None, legacy_matlab: str | None = None,
                tools_dir: str | None = None, variants: list[str] | None = None, log=print):
    out = mouse_dir / OUT; out.mkdir(exist_ok=True)
    # the lab's MATLAB registration: run by MATLAB (run_reg_compare_legacy.m) when its code is found, else dropped in by hand
    legacy_dir = None
    if add_legacy:
        legacy_dir = Path(legacy_matlab) if legacy_matlab else find_legacy_dir(mouse_dir)
        if legacy_matlab and not (Path(legacy_matlab) / "MovieProcessing").exists() and not as_root:
            log(f"  --legacy-matlab {legacy_matlab}: no MovieProcessing\\ folder inside (as seen from here) — MATLAB will check again")
        if legacy_dir is None:
            log("  legacy MATLAB code not found (lagacy_matlab\\Matlab next to the mouse folders; or --legacy-matlab DIR): "
                "D_legacy is expected to be filled by hand")
        else:
            log(f"  legacy MATLAB code: {legacy_dir} -> run_reg_compare_legacy.m will make the D_legacy / E_legacy_both movies")
    legacy_jobs = []
    all_runs = _runs_of(mouse_dir)
    chosen = []
    for key in runs:
        hits = [r for r in all_runs if key in r["run"]]
        if not hits:
            log(f"  {key}: no such run in this mouse folder — skipped")
            continue
        chosen.append(hits[0])
    if not chosen:
        raise SystemExit("no runs chosen")
    seen = lambda p: _as_seen(p, mouse_dir, as_root)     # noqa: E731
    batch_rows, res_list, presets, preset_src, manifest = [], [], [], [], {"mouse": mouse_dir.name, "runs": []}
    for r in chosen:
        tif = Path(r["tif"]); f = aqua_files(tif)
        stem = tif.stem
        try:
            info = json.loads(f["json"].read_text()) if f["json"].exists() else {}
        except Exception:
            info = {}
        spf = float(info.get("seconds_per_frame", 2.0) or 2.0)
        N = int(bin_frames or info.get("bin_frames") or 31)
        sbx = Path(info.get("source_sbx", "")) if info.get("source_sbx") else None
        if sbx is None or not sbx.exists():
            cand = sorted(tif.parent.glob("*.sbx"))
            sbx = cand[0] if cand else None
        vals, src = _preset_for(mouse_dir, r, opts_default, log=log)
        vals = dict(vals); vals["frameRate"] = f"{spf:.6g}"
        # two presets per run: as the main batch (registrateCorrect 2) and without AQuA2's registration (1)
        p_reg = dict(vals); p_reg["registrateCorrect"] = "2"
        p_noreg = dict(vals); p_noreg["registrateCorrect"] = "1"
        i_reg = len(presets) + 1; presets += [p_reg, p_noreg]; preset_src += [f"{r['run']}: {src}", f"{r['run']}: {src}, registrateCorrect=1"]
        i_noreg = i_reg + 1
        rdir = out / r["run"].replace("_bin31f_1p98s", ""); rdir.mkdir(exist_ok=True)
        log(f"\n{r['run']} [{r['condition']}] — settings: {src}; raw: {sbx.name if sbx else 'NOT FOUND'}")
        entry = {"run": r["run"], "experiment": r["experiment"], "condition": r["condition"], "tif": seen(tif), "seconds_per_frame": spf,
                 "bin_frames": N, "variants": []}
        var_list = VARIANTS + ([LEGACY] if add_legacy else []) + ([LEGACY_BOTH] if add_legacy and legacy_dir is not None else [])
        if variants:
            keys = [v.strip().upper() for v in variants if v.strip()]
            var_list = [v for v in var_list if v[0][0].upper() in keys or v[0].upper() in keys]
        prereg_tif = None
        legacy_tif = None
        for name, desc, regc, kind in var_list:
            vdir = rdir / name; vdir.mkdir(exist_ok=True)
            vt = vdir / tif.name
            if kind == "aqua":
                _link_or_copy(tif, vt)
                for k in ("json", "behavior"):
                    if f[k].exists():
                        shutil.copy2(f[k], vdir / f[k].name)
                fr = Path(str(tif.with_suffix("")) + "_frames.csv")
                if fr.exists():
                    shutil.copy2(fr, vdir / fr.name)
                dj = Path(str(tif.with_suffix("")) + "_frames_decisions.json")
                if dj.exists():
                    shutil.copy2(dj, vdir / dj.name)
            elif kind == "prereg":
                if prereg_tif is None:
                    if sbx is None:
                        log(f"  {name}: no .sbx next to the tiff — cannot register the raw frames; variant skipped")
                        continue
                    if vt.exists() and not overwrite:
                        log(f"  {name}: {vt.name} exists — kept (--overwrite to redo)")
                    else:
                        from afferent2p.fullreg import register_bin_sbx
                        log(f"  {name}: registering the raw frames of {sbx.name} (a few minutes) …")
                        register_bin_sbx(sbx, N, vdir, chan=1, behavior_csv=f["behavior"] if f["behavior"].exists() else None,
                                         overwrite=overwrite, log=log)
                    prereg_tif = vt
                else:                                       # C: the same movie as B
                    for p in prereg_tif.parent.iterdir():
                        if p.is_file() and p.name.startswith(stem) and "_AQuA2" not in p.name and "_motion" not in p.name:
                            if p.suffix == ".tif" and p.name == prereg_tif.name:
                                _link_or_copy(p, vdir / p.name)
                            else:
                                shutil.copy2(p, vdir / p.name)
            elif kind == "legacy":
                if legacy_dir is not None:
                    if sbx is None:
                        log(f"  {name}: no .sbx next to the tiff — the legacy registration needs the raw frames; variant skipped")
                        continue
                    both_dir = rdir / LEGACY_BOTH[0] if any(v[0] == LEGACY_BOTH[0] for v in var_list) else None
                    if vt.exists() and not overwrite:
                        log(f"  {name}: {vt.name} exists — kept (--overwrite to redo it in MATLAB)")
                    else:
                        log(f"  {name}: MATLAB will register the raw frames of {sbx.name} with the legacy chain (run_reg_compare_legacy.m)")
                    if tif.stem.startswith(sbx.stem + "_"):
                        tag = tif.stem[len(sbx.stem) + 1:]
                    elif "_bin" in tif.stem:
                        tag = "bin" + tif.stem.split("_bin", 1)[1]
                    else:
                        tag = ""
                    legacy_jobs.append((seen(sbx), seen(vdir), N, tag, spf, seen(f["behavior"]) if f["behavior"].exists() else "",
                                        seen(both_dir) if both_dir else ""))
                    legacy_tif = vt
                elif not vt.exists():
                    log(f"  {name}: put the lab-registered binned tiff there as {vt.name} (+ its _behavior.csv) and run prepare again; skipped for now")
                    continue
            elif kind == "legacy_both":
                if legacy_tif is None:
                    continue                                # made by the MATLAB step (copied from D) — queued below
            pidx = i_reg if regc == 2 else i_noreg
            res = Path(str(vt.with_suffix("")) + "_AQuA2.mat")
            done = res.exists() and res.stat().st_size > 0
            if not done or overwrite:
                batch_rows.append((seen(vt), pidx, seen(vdir)))
            res_list.append("    '" + _mat(seen(res)) + "'")
            entry["variants"].append({"name": name, "description": desc, "registrateCorrect": regc, "tif": seen(vt), "preset": pidx,
                                      "aqua_done": bool(done)})
            log(f"  {name}: {'result exists' if done and not overwrite else 'queued'} (Preset{pidx}, registrateCorrect={regc}) — {desc}")
        manifest["runs"].append(entry)
    # parameters_for_batch.csv (same layout as aqua_batch.py)
    lines = ["Name,Variable,Type," + ",".join(f"Preset{i + 1}" for i in range(len(presets)))]
    for name, var, typ, default in OPT_TEMPLATE_ROWS:
        if not var:
            lines.append("," * (2 + len(presets)))
            continue
        lines.append(",".join([f'"{name}"' if "," in name else name, var, typ] + [p.get(var, default) for p in presets]))
    (out / "parameters_for_batch.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    blines = ["inputPath,preset,outputPath,cellMaskPath,landmarkMaskPath"] + [f"{t},{p},{o},," for t, p, o in batch_rows]
    (out / "batch.csv").write_text("\n".join(blines) + "\n", encoding="utf-8")
    (out / "run_reg_compare_aqua.m").write_text(AQUA_SCRIPT.format(
        aqua_dir=_mat(aqua_dir), batch_csv=_mat(seen(out / "batch.csv")), params_csv=_mat(seen(out / "parameters_for_batch.csv"))), encoding="utf-8")
    (out / "run_reg_compare_cfu.m").write_text(CFU_SCRIPT.format(
        aqua_dir=_mat(aqua_dir), mouse_dir=_mat(seen(out)), overlap=cfu_overlap, res_list="\n".join(res_list) if res_list else "    % (none)",
        min_evt=int(cfu_min_events), overwrite="true" if overwrite else "false"), encoding="utf-8")
    both = BOTH_SCRIPT.format(aqua_script=_mat(seen(out / "run_reg_compare_aqua.m")), cfu_script=_mat(seen(out / "run_reg_compare_cfu.m")))
    legacy_script = out / "run_reg_compare_legacy.m"
    if legacy_jobs:
        tools = tools_dir or str(HERE)
        jobs = "\n".join("    '%s', '%s', %d, '%s', %.6g, '%s', '%s';" % (_mat(a), _mat(b), n, _mat(t), sp, _mat(bc), _mat(bd))
                         for a, b, n, t, sp, bc, bd in legacy_jobs)
        legacy_script.write_text(LEGACY_SCRIPT.replace("@TOOLS@", _mat(tools)).replace("@LEGACY@", _mat(str(legacy_dir)))
                                 .replace("@JOBS@", jobs).replace("@OVERWRITE@", "true" if overwrite else "false"), encoding="utf-8")
        both = both.replace("run('", "run('" + _mat(seen(legacy_script)) + "');\nrun('", 1)
        both = both.replace("%% run_aqua_and_cfu.m — generated by aqua_batch.py: the AQuA2 batch, then the CFU batch",
                            "%% run_reg_compare.m — generated by reg_compare.py: the legacy MATLAB registration, the AQuA2 batch, then the CFU batch")
    else:
        both = both.replace("%% run_aqua_and_cfu.m — generated by aqua_batch.py:", "%% run_reg_compare.m — generated by reg_compare.py:")
        if legacy_script.exists():
            legacy_script.unlink()
    (out / "run_reg_compare.m").write_text(both, encoding="utf-8")
    manifest["presets"] = [{"preset": i + 1, "source": s, "values": p} for i, (s, p) in enumerate(zip(preset_src, presets))]
    manifest["built"] = time.time(); manifest["aqua_dir"] = aqua_dir
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    log(f"\n{len(batch_rows)} variant movie(s) queued for AQuA2 -> {out}"
        + (f"\n{len(legacy_jobs)} legacy MATLAB registration(s) queued first (run_reg_compare_legacy.m; stage 2 is slow without a parallel pool: "
           "expect 15-60 min per recording)" if legacy_jobs else "")
        + f"\nNext, in MATLAB (one paste):\n  run('{seen(out / 'run_reg_compare.m')}')\nthen: python reg_compare.py report \"{mouse_dir}\"")
    return out


