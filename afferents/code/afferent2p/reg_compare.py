def find_legacy_dir(mouse_dir: Path) -> Path | None:
    """The lab's MATLAB code (a folder with MovieProcessing\\CorrectExpt.m): lagacy_matlab\\Matlab or
    legacy_matlab\\Matlab next to the mouse folder or one level up."""
    for base in (mouse_dir.parent, mouse_dir.parent.parent, mouse_dir):
        for name in ("lagacy_matlab", "legacy_matlab", "Matlab", "matlab"):
            for cand in (base / name / "Matlab", base / name):
                if (cand / "MovieProcessing" / "CorrectExpt.m").exists():
                    return cand
    return None


