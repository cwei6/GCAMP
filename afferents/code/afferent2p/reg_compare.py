def _fibre_share(events, meanimg, um_per_px: float) -> float:
    """Share of the events whose centre lies on the (dilated) fibre mask of the variant's own mean image."""
    if events is None or len(events) == 0 or meanimg is None:
        return np.nan
    try:
        from afferent2p.cfu_shape import fibre_mask_for
        fm, _ = fibre_mask_for(meanimg, um_per_px, dilate_px=3)
        yy = np.clip(np.round(events["y_px"].to_numpy(float)).astype(int) - 1, 0, fm.shape[0] - 1)
        xx = np.clip(np.round(events["x_px"].to_numpy(float)).astype(int) - 1, 0, fm.shape[1] - 1)
        return float(fm[yy, xx].mean())
    except Exception:
        return np.nan


def _align_means(ref_img: np.ndarray, img: np.ndarray) -> tuple[float, float, float]:
    """(dy, dx, corr): where the content of `img` sits relative to `ref_img`
    (both mean images, any sizes — zero-padded to a common frame), by the
    motion module's phase correlation at full resolution."""
    from afferent2p.motion import _Matcher
    H = max(ref_img.shape[0], img.shape[0]); W = max(ref_img.shape[1], img.shape[1])
    a = np.zeros((H, W), np.float32); b = np.zeros((H, W), np.float32)
    a[:ref_img.shape[0], :ref_img.shape[1]] = ref_img; b[:img.shape[0], :img.shape[1]] = img
    M = _Matcher(a, max_shift=min(80, H // 3, W // 3), sigma=1.0, hp=30.0, down=1)
    return M.shift(b)


def _to_common(events, dy: float, dx: float):
    """Event centres (1-based, this variant's result frame) -> 0-based coordinates
    of the reference variant's result frame (the variant's mean image sits
    (dy, dx) from the reference's)."""
    y = events["y_px"].to_numpy(float) - 1 - dy
    x = events["x_px"].to_numpy(float) - 1 - dx
    return y, x


def _match(ev_a, ev_b, max_dist: float = 15.0, t_pad: int = 2) -> np.ndarray:
    """For every event of a: index of a matching event of b (centre within max_dist px in the raw frame, times overlapping), else -1."""
    out = np.full(len(ev_a), -1, int)
    if len(ev_a) == 0 or len(ev_b) == 0:
        return out
    ya, xa = ev_a["raw_y"].to_numpy(float), ev_a["raw_x"].to_numpy(float)
    yb, xb = ev_b["raw_y"].to_numpy(float), ev_b["raw_x"].to_numpy(float)
    ta0, ta1 = ev_a["t0_frame"].to_numpy(float), ev_a["t1_frame"].to_numpy(float)
    tb0, tb1 = ev_b["t0_frame"].to_numpy(float), ev_b["t1_frame"].to_numpy(float)
    used = np.zeros(len(ev_b), bool)
    for i in range(len(ev_a)):
        d = np.hypot(yb - ya[i], xb - xa[i])
        ok = (d <= max_dist) & ~used & (tb0 <= ta1[i] + t_pad) & (tb1 >= ta0[i] - t_pad)
        if ok.any():
            j = int(np.argmin(np.where(ok, d, np.inf))); out[i] = j; used[j] = True
    return out


def cmd_report(mouse_dir: Path, um_per_px: float = 0.792, log=print):
    import pandas as pd
    import tifffile as tf
    from afferent2p.motion import run_motion
    from afferent2p.tune import crop_offset
    from afferent2p.report import _esc, _num, page_html
    out = mouse_dir / OUT
    man = json.loads((out / "manifest.json").read_text())
    rows, ev_rows, sections = [], [], []
    for entry in man["runs"]:
        short = entry["run"].replace("_bin31f_1p98s", "").replace(mouse_dir.name + "_", "")
        spf = float(entry.get("seconds_per_frame", 2.0))
        per_variant = {}
        for v in entry["variants"]:
            vt = Path(relocate(v["tif"], mouse_dir))
            if not vt.exists():
                continue
            f = aqua_files(vt)
            d = {"run": short, "condition": entry.get("condition", ""), "variant": v["name"], "registrateCorrect": v["registrateCorrect"],
                 "aqua_done": f["res"].exists()}
            # the input movie's own motion and the residual after AQuA2 (res.datOrg1)
            try:
                summ = run_motion(vt, log=log)
            except Exception as e:
                log(f"  {short} {v['name']}: motion check failed ({e})"); summ = None
            if summ:
                d.update({"input_shift_median_px": summ["shift_median"], "input_shift_max_px": summ["shift_max"],
                          "input_jumps_per_min": summ["jumps_ge2_per_min"], "input_corr_shift_speed": summ.get("corr_shift_speed"),
                          "residual_rigid_p95_px": summ.get("residual_rigid_p95"), "deformation_median_px": summ.get("nonrigid_median"),
                          "deformation_jumps_per_min": summ.get("nonrigid_jumps_per_min"),
                          "onsets_near_motion": summ["events"].get("near_motion"), "onsets_near_motion_expected": summ["events"].get("expected_near_motion"),
                          "onsets_near_motion_ratio": summ["events"].get("ratio_motion"), "motion_verdict": summ["verdict"][0]})
            # events / CFUs
            ev_csv = Path(str(vt.with_suffix("")) + "_AQuA2_events.csv")
            ev = None
            if ev_csv.exists():
                try:
                    ev = pd.read_csv(ev_csv)
                except Exception:
                    ev = None
            minutes = np.nan
            try:
                info = json.loads(f["json"].read_text()) if f["json"].exists() else {}
                minutes = float(info.get("frames_out", 0)) * spf / 60.0
            except Exception:
                info = {}
            crop_in_raw = int((info.get("registration") or {}).get("crop_in_raw_px", 0)) if isinstance(info.get("registration"), dict) else 0
            meanimg = None
            mi = Path(str(vt.with_suffix("")) + "_AQuA2_meanimg.tif")
            if mi.exists():
                try:
                    meanimg = np.asarray(tf.imread(str(mi)), np.float32)
                except Exception:
                    meanimg = None
            off = (0, 0)
            if meanimg is not None:
                try:
                    mp = f["meanproj"]
                    raw_mean = np.asarray(tf.imread(str(mp)), np.float32) if mp.exists() else None
                    o = crop_offset(raw_mean, meanimg) if raw_mean is not None else None
                    off = (o[0], o[1]) if o else (0, 0)
                except Exception:
                    off = (0, 0)
            n_ev = 0 if ev is None else len(ev)
            d.update({"minutes": minutes, "events": n_ev, "events_per_min": (n_ev / minutes) if minutes and np.isfinite(minutes) and minutes > 0 else np.nan,
                      "events_on_fibre_share": _fibre_share(ev, meanimg, um_per_px),
                      "event_dff_median": float(np.nanmedian(ev["dff_max"])) if ev is not None and len(ev) and "dff_max" in ev.columns else np.nan,
                      "event_duration_median_s": float(np.nanmedian((ev["t1_frame"] - ev["t0_frame"] + 1) * spf)) if ev is not None and len(ev) else np.nan,
                      "event_area_median_um2": float(np.nanmedian(ev["area_um2"])) if ev is not None and len(ev) and "area_um2" in ev.columns else np.nan,
                      "result_shape": list(meanimg.shape) if meanimg is not None else None, "crop_offset_in_input": list(off), "input_crop_in_raw": crop_in_raw})
            try:
                c = read_cfu(f["cfu"]) if f["cfu"].exists() else None
                d["cfus"] = int(c["n"]) if c else np.nan
            except Exception:
                d["cfus"] = np.nan
            per_variant[v["name"]] = {"row": d, "events": ev.copy() if ev is not None else None, "meanimg": meanimg, "tif": vt, "summ": summ}
            rows.append(d)
        # one coordinate frame for the matching: the first variant with a mean image; the others are aligned to it
        ref_name = next((n for n in per_variant if per_variant[n]["meanimg"] is not None), None)
        for name, pv in per_variant.items():
            ev = pv["events"]
            if ev is None or len(ev) == 0:
                continue
            dy = dx = 0.0; cc = 1.0
            if ref_name is not None and name != ref_name and pv["meanimg"] is not None:
                try:
                    dy, dx, cc = _align_means(per_variant[ref_name]["meanimg"], pv["meanimg"])
                except Exception:
                    dy = dx = 0.0; cc = np.nan
            pv["row"]["offset_vs_" + (ref_name or "ref")] = [round(float(dy), 1), round(float(dx), 1)]; pv["row"]["align_corr"] = float(cc)
            ry, rx = _to_common(ev, dy, dx)
            ev["raw_y"] = ry; ev["raw_x"] = rx
        # which events are shared between the variants (in the raw frame)
        names = [n for n in per_variant if per_variant[n]["events"] is not None]
        for a in names:
            ea = per_variant[a]["events"]
            d = per_variant[a]["row"]
            for b in names:
                if a == b:
                    continue
                m = _match(ea, per_variant[b]["events"])
                d[f"found_in_{b}"] = int((m >= 0).sum())
            if len(names) > 1:
                others = [n for n in names if n != a]
                in_all = np.ones(len(ea), bool); in_none = np.ones(len(ea), bool)
                for b in others:
                    m = _match(ea, per_variant[b]["events"]); in_all &= (m >= 0); in_none &= (m < 0)
                d["found_in_every_variant"] = int(in_all.sum()); d["found_only_here"] = int(in_none.sum())
                if len(ea):
                    ea["only_here"] = in_none; ea["in_every_variant"] = in_all
                for k in range(len(ea)):
                    ev_rows.append({"run": short, "variant": a, "event": int(ea["event"].iloc[k]), "t0_frame": int(ea["t0_frame"].iloc[k]),
                                    "raw_y": float(ea["raw_y"].iloc[k]), "raw_x": float(ea["raw_x"].iloc[k]), "dff_max": float(ea["dff_max"].iloc[k]) if "dff_max" in ea.columns else np.nan,
                                    "in_every_variant": bool(in_all[k]), "only_here": bool(in_none[k])})
        # figure: mean image + event boxes per variant, and the input motion of A vs B
        try:
            sections.append(_run_section(short, entry, per_variant, mouse_dir, spf, log=log))
        except Exception as e:
            log(f"  {short}: figure failed ({e})")
            sections.append(f"<h2>{_esc(short)}</h2><p class='warn'>figure failed: {_esc(e)}</p>")
    df = pd.DataFrame(rows)
    df.to_csv(out / "reg_compare_summary.csv", index=False)
    if ev_rows:
        pd.DataFrame(ev_rows).to_csv(out / "reg_compare_events.csv", index=False)
    # the html
    cols = ["run", "condition", "variant", "registrateCorrect", "aqua_done", "input_shift_median_px", "input_shift_max_px", "input_jumps_per_min",
            "residual_rigid_p95_px", "deformation_median_px", "events", "events_per_min", "events_on_fibre_share", "event_dff_median",
            "cfus", "onsets_near_motion", "onsets_near_motion_expected", "found_in_every_variant", "found_only_here", "motion_verdict"]
    cols = [c for c in cols if c in df.columns]
    head = "".join(f"<th>{_esc(c.replace('_', ' '))}</th>" for c in cols)
    body = ""
    for r in df.to_dict("records"):
        def cell(v):
            if isinstance(v, (bool, np.bool_)):
                return "yes" if v else "no"
            if isinstance(v, (int, np.integer)):
                return str(int(v))
            if isinstance(v, (float, np.floating)):
                return _num(v, 0) if float(v).is_integer() and abs(v) >= 1 else _num(v, 2)
            return str(v)
        body += "<tr>" + "".join(f"<td>{_esc(cell(r[c]))}</td>" for c in cols) + "</tr>"
    intro = (f"<h1>{_esc(mouse_dir.name)} — registration comparison</h1><p class='byline'>Generated {time.strftime('%Y-%m-%d %H:%M')} by reg_compare.py. "
             "A = binned tiff as recorded, AQuA2 registers it (the current route); B = raw frames registered before binning (Python), AQuA2 does not register; "
             "C = that pre-registered tiff and AQuA2 registers again; D (if present) = the lab's legacy MATLAB registration (CorrectExpt DFT + RegisterSBX rigid), "
             "AQuA2 does not register; E = the same and AQuA2 registers again. Same AQuA2 settings otherwise.</p>"
             "<p>How to read it: the <b>input</b> columns say how much the movie AQuA2 was given still moved (B/C should be far steadier than A); "
             "<b>residual</b> and <b>deformation</b> say what is left in the movie AQuA2 detected on; <b>events on fibre share</b> and "
             "<b>onsets near motion</b> (vs the number expected by chance) say whether a variant detects motion rather than activity; "
             "<b>found in every variant</b> / <b>found only here</b> say whether the routes find the same events. If A's events are "
             "found by the pre-registered variants as well, with no excess of onsets on moving frames, AQuA2's own registration is enough for that recording.</p>"
             "<div class='scroll'><table class='qc'><thead><tr>" + head + "</tr></thead><tbody>" + body + "</tbody></table></div>")
    html = page_html(f"{mouse_dir.name} — registration comparison", intro + "".join(sections),
                     ".scroll { overflow-x: auto; } table.qc { font-size: 12px; } h2 { margin-top: 26px; }", "")
    (out / "reg_compare.html").write_text(html, encoding="utf-8")
    pd.set_option("display.width", 240); pd.set_option("display.max_columns", 30)
    log(df[cols].round(2).to_string(index=False))
    log(f"\nwrote {out / 'reg_compare_summary.csv'}, {out / 'reg_compare.html'}")
    return df


def _run_section(short: str, entry: dict, per_variant: dict, mouse_dir: Path, spf: float, log=print) -> str:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle
    from afferent2p.report import _fig_uri, _esc, _figure, _stretch, _num
    from afferent2p.motion import read_motion
    names = list(per_variant)
    n = len(names)
    fig, axes = plt.subplots(2, max(n, 1), figsize=(5.2 * max(n, 1), 8.2), gridspec_kw=dict(height_ratios=[1.3, 1.0], hspace=0.25, wspace=0.08))
    axes = np.atleast_2d(axes)
    if axes.shape[0] == 1:
        axes = axes.T
    for k in range(1, axes.shape[1]):
        axes[1, k].sharey(axes[1, 0])
    for k, name in enumerate(names):
        pv = per_variant[name]; ax = axes[0, k]
        img = pv["meanimg"]
        if img is None:
            ax.text(0.5, 0.5, "no AQuA2 result yet", ha="center", va="center", transform=ax.transAxes); ax.set_axis_off()
        else:
            v0, v1 = _stretch(img, 0.5, 99.8)
            ax.imshow(img, cmap="gray", vmin=v0, vmax=v1, interpolation="nearest"); ax.set_axis_off()
            ev = pv["events"]
            if ev is not None and len(ev) and {"y0", "y1", "x0", "x1"} <= set(ev.columns):
                for r in ev.itertuples(index=False):
                    only = bool(getattr(r, "only_here", False)) if "only_here" in ev.columns else False
                    ax.add_patch(Rectangle((float(r.x0) - 1.5, float(r.y0) - 1.5), float(r.x1) - float(r.x0) + 1, float(r.y1) - float(r.y0) + 1,
                                           fill=False, ec="#ffa600" if not only else "#d64545", lw=0.8))
        d = pv["row"]
        ax.set_title(f"{name}: {d.get('events', 0)} events" + (f" ({_num(100 * d.get('events_on_fibre_share', np.nan), 0)} % on fibres)" if np.isfinite(d.get('events_on_fibre_share', np.nan)) else "")
                     + (f", {int(d['cfus'])} CFUs" if np.isfinite(d.get("cfus", np.nan)) else "")
                     + (f"\nfound in every variant {d['found_in_every_variant']}, only here {d['found_only_here']}" if "found_in_every_variant" in d else ""), fontsize=9)
        # motion of the input movie (what AQuA2 was given) and the residual after it
        ax2 = axes[1, k]
        summ = pv["summ"]
        _, mdf = read_motion(pv["tif"])
        if mdf is not None:
            t = mdf["time_s"].to_numpy(float) / 60.0
            ax2.plot(t, mdf["shift"], lw=0.7, color="#1f77b4", label="input: |shift| of the frame")
            if "nonrigid" in mdf.columns:
                ax2.plot(t, mdf["nonrigid"], lw=0.7, color="#7a5195", label="after AQuA2: deformation")
            if "res_dy" in mdf.columns:
                ax2.plot(t, np.hypot(mdf["res_dy"], mdf["res_dx"]), lw=0.7, color="#ffa600", label="after AQuA2: rigid residual")
            if summ and summ.get("events", {}).get("n_onsets"):
                ev = pv["events"]
                if ev is not None:
                    for t0 in ev["t0_frame"].to_numpy(float):
                        ax2.axvline((t0 - 0.5) * spf / 60.0, color="#2a9d8f", lw=0.5, alpha=0.5, zorder=0)
            sp = mdf["speed"].to_numpy(float)
            if np.isfinite(sp).any() and np.nanmax(sp) > 0:
                ax3 = ax2.twinx(); ax3.fill_between(t, 0, np.nan_to_num(sp), color="#bbb", alpha=0.35, lw=0, step="mid"); ax3.set_yticks([])
            ax2.set_xlabel("minutes", fontsize=8); ax2.tick_params(labelsize=7)
            if k == 0:
                ax2.set_ylabel("px", fontsize=8)
            ax2.legend(fontsize=6.5, loc="upper right", frameon=False)
            ax2.set_title(f"input shift median {_num(d.get('input_shift_median_px', np.nan), 1)} px, max {_num(d.get('input_shift_max_px', np.nan), 1)}; "
                          f"deformation after AQuA2 {_num(d.get('deformation_median_px', np.nan), 1)} px", fontsize=8)
        else:
            ax2.set_axis_off()
    fig.suptitle(f"{short} [{entry.get('condition', '')}] — the same recording, {n} registration route{'s' if n != 1 else ''} (orange = event box, red = found by this variant only; "
                 "grey = running speed, teal = event onsets)", fontsize=10, x=0.01, ha="left")
    uri = _fig_uri(fig, dpi=90)
    return f"<h2 id='run-{_esc(short)}'>{_esc(short)}</h2>" + _figure(uri, "")


# ----------------------------------------------------------------------------- CLI

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("pick", help="rank the recordings by locomotion and measured movement")
    p.add_argument("mouse", type=Path); p.add_argument("--measure", type=int, default=0, help="also measure the movement of the N most-running recordings that have no _motion.json yet (20-60 s each)")
    p = sub.add_parser("prepare", help="build the variants and the MATLAB batch for the chosen recordings")
    p.add_argument("mouse", type=Path); p.add_argument("--runs", required=True, help="comma-separated run keys, e.g. 260921_004,260921_006")
    p.add_argument("--aqua-dir", default=None, help="AQuA2 folder as MATLAB sees it (default: the one in aqua_batch\\manifest.json)")
    p.add_argument("--as-root", default=None, help="the mouse folder as the MATLAB PC sees it (e.g. Z:\\...)")
    p.add_argument("--add-legacy", action="store_true", help="also the lab's legacy MATLAB registration (D_legacy, E_legacy_both; run by MATLAB when its code is found, else a D_legacy folder you filled by hand)")
    p.add_argument("--legacy-matlab", default=None, help="the legacy MATLAB code folder (holds MovieProcessing\\) as MATLAB sees it; default: lagacy_matlab\\Matlab next to the mouse folders")
    p.add_argument("--tools-dir", default=None, help="this afferent2p folder as MATLAB sees it (legacy_register_run.m); default: where reg_compare.py is")
    p.add_argument("--variants", default=None, help="subset of the variants, e.g. A,D,E (letters or names)")
    p.add_argument("--bin-frames", type=int, default=None); p.add_argument("--cfu-min-events", type=int, default=1); p.add_argument("--cfu-overlap", type=float, default=0.5)
    p.add_argument("--opts", type=Path, default=None, help="settings file when the main batch has none for the run")
    p.add_argument("--overwrite", action="store_true", help="redo the pre-registration and queue every variant again")
    p = sub.add_parser("report", help="compare the variants once MATLAB has run")
    p.add_argument("mouse", type=Path); p.add_argument("--um-per-px", type=float, default=0.792)
    a = ap.parse_args()
    mouse = Path(a.mouse).resolve()
    if a.cmd == "pick":
        cmd_pick(mouse, measure=a.measure)
    elif a.cmd == "prepare":
        aqua_dir = a.aqua_dir
        if not aqua_dir:
            man = mouse / "aqua_batch" / "manifest.json"
            aqua_dir = json.loads(man.read_text()).get("aqua_dir", "") if man.exists() else ""
            if not aqua_dir:
                raise SystemExit("--aqua-dir needed (no aqua_batch\\manifest.json with one)")
        cmd_prepare(mouse, [s.strip() for s in a.runs.split(",") if s.strip()], aqua_dir, a.as_root, a.add_legacy, a.bin_frames,
                    a.cfu_min_events, a.cfu_overlap, a.overwrite, a.opts, legacy_matlab=a.legacy_matlab, tools_dir=a.tools_dir,
                    variants=[v for v in a.variants.split(",")] if a.variants else None)
    else:
        cmd_report(mouse, um_per_px=a.um_per_px)


if __name__ == "__main__":
    main()
