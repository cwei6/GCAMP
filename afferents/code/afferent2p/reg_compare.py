def _runs_of(mouse_dir: Path) -> list[dict]:
    """[{run, experiment, condition, tif}] from the batch manifest, else by discovery."""
    man = mouse_dir / "aqua_batch" / "manifest.json"
    out = []
    if man.exists():
        m = json.loads(man.read_text())
        for e in m.get("experiments", []):
            for r in e.get("runs", []):
                out.append({"run": r["run"], "experiment": e["name"], "condition": r.get("condition", ""),
                            "tif": relocate(r["tif"], mouse_dir), "preset": r.get("preset")})
        if out:
            return out
    from afferent2p.aqua_io import find_binned_tifs
    from afferent2p.plan import skip_parts
    for d in sorted({p.parent for p in mouse_dir.rglob("*_bin*s.tif")}):
        if skip_parts(d.relative_to(mouse_dir).parts) or OUT in d.relative_to(mouse_dir).parts:
            continue
        for t in find_binned_tifs(d):
            out.append({"run": t.stem, "experiment": "?", "condition": "?", "tif": t, "preset": None})
    return out


def cmd_pick(mouse_dir: Path, measure: int = 0, log=print):
    """Rank the recordings by locomotion and (where measured) by movement."""
    import pandas as pd
    from afferent2p.motion import read_motion, run_motion
    rows = []
    runs = _runs_of(mouse_dir)
    for r in runs:
        tif = Path(r["tif"]); f = aqua_files(tif)
        d = {"run": r["run"].replace("_bin31f_1p98s", ""), "experiment": r["experiment"], "condition": r["condition"],
             "running_pct": np.nan, "onsets": np.nan, "events": np.nan}
        if f["behavior"].exists():
            try:
                b = pd.read_csv(f["behavior"]); run = b["still_fraction"].to_numpy(float) < 0.5
                d["running_pct"] = 100 * run.mean(); d["onsets"] = int((np.diff(run.astype(int)) == 1).sum())
            except Exception:
                pass
        ev = Path(str(tif.with_suffix("")) + "_AQuA2_events.csv")
        if ev.exists():
            try:
                d["events"] = len(pd.read_csv(ev))
            except Exception:
                pass
        summ, _ = read_motion(tif)
        if summ is None and measure and len([x for x in rows if np.isfinite(x.get("shift_median", np.nan))]) < measure and tif.exists():
            try:
                summ = run_motion(tif, log=log)
            except Exception:
                summ = None
        if summ:
            d.update({"shift_median": summ.get("shift_median"), "shift_max": summ.get("shift_max"), "jumps_per_min": summ.get("jumps_ge2_per_min"),
                      "corr_shift_speed": summ.get("corr_shift_speed"), "events_near_motion": summ.get("events", {}).get("near_motion"),
                      "motion_verdict": (summ.get("verdict") or ["", ""])[0]})
        rows.append(d)
    df = pd.DataFrame(rows)
    if len(df):
        df = df.sort_values(["running_pct", "onsets"], ascending=False)
    pd.set_option("display.width", 220); pd.set_option("display.max_columns", 20)
    log(df.round(2).to_string(index=False))
    out = mouse_dir / OUT; out.mkdir(exist_ok=True)
    df.to_csv(out / "pick.csv", index=False)
    top = df[df["running_pct"] >= 40].head(4) if len(df) else df
    if len(df) and len(top) == 0:
        top = df.head(4)
    log("\nSuggested (most running, with locomotion onsets and events): " + ", ".join(top["run"].tolist())
        + "\n  python reg_compare.py prepare \"" + str(mouse_dir) + "\" --runs " + ",".join(t.split("_", 1)[1] if "_" in t else t for t in top["run"].tolist()))
    return df


