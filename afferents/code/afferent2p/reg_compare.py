#!/usr/bin/env python3
"""reg_compare — is AQuA2's own registration enough? Three ways of registering
the same recordings, the same AQuA2 settings, compared on the detections.

    python reg_compare.py pick    "<mouse folder>"                      # which recordings move most (running, shifts)
    python reg_compare.py prepare "<mouse folder>" --runs 260921_004,260921_006 [--as-root Z:\\...]
    -> in MATLAB:  run('<mouse>\\reg_compare\\run_reg_compare.m')         (AQuA2 + CFU batch on every variant)
    python reg_compare.py report  "<mouse folder>"                      # tables + figures + reg_compare.html

The three variants of every chosen recording (same tuned settings as the
main batch — read from aqua_batch\\manifest.json — except the registration):

  A_aqua2   the binned tiff as the pipeline makes it; AQuA2 registers it
            itself (registrateCorrect = 2: one whole-pixel translation per
            2-s frame against the mean of its first 10 frames) — the current
            route;
  B_prereg  the RAW 15.6-Hz frames registered first (afferent2p/fullreg.py:
            rigid translation per raw frame to a still-period reference,
            the legacy MATLAB CorrectExpt / RegisterSBX operation in Python),
            then binned; AQuA2 told NOT to register (registrateCorrect = 1);
  C_both    the same pre-registered tiff, AQuA2 registering again on top
            (registrateCorrect = 2).

Two more variants use the lab's legacy MATLAB registration itself
(ProcessScanboxData_concatFirst.m chain: CorrectExpt DFT + RegisterSBX 'rigid',
run per recording by legacy_register_run.m in this folder) when `prepare
--add-legacy` finds the legacy code (lagacy_matlab\\Matlab next to the mouse
folders, or --legacy-matlab DIR): the generated run_reg_compare.m then runs
that registration in MATLAB first,

  D_legacy  the lab-registered binned tiff, AQuA2 told NOT to register (1);
  E_legacy_both  the same tiff, AQuA2 registering again (2).

Without the legacy code, `--add-legacy` expects a folder <run>\\D_legacy\\ you
filled by hand (a binned tiff with the same stem as the others + its
_behavior.csv). --variants picks a subset (e.g. A,D,E).

The report measures, per recording and variant: the motion of the movie
AQuA2 was given (shift / jumps, afferent2p.motion), what is left after AQuA2
(residual, deformation), events (number, per minute, share on the fibre
mask, onsets on moving frames vs chance), CFUs, and which events are found
by every variant versus by one only (centres mapped into the raw frame and
matched within 15 px with overlapping times). Output: reg_compare\\
reg_compare_summary.csv, reg_compare_events.csv, one figure per recording
(mean image + event boxes per variant, shift traces), reg_compare.html.

The recordings' own results in their run folders are not touched; the
variants live under <mouse>\\reg_compare\\ (which every other tool skips).
"""
