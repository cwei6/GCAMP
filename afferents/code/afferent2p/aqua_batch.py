def launch_gui():
    import queue
    import threading
    import tkinter as tk
    from tkinter import filedialog, ttk

    class App(tk.Tk):
        def __init__(self):
            super().__init__()
            self.title("aqua_batch — AQuA2 batch jobs per FOV")
            self.geometry("900x600")
            self.folders: list[Path] = []
            self.q: queue.Queue = queue.Queue()
            top = ttk.Frame(self); top.pack(fill="x", padx=8, pady=6)
            ttk.Button(top, text="Add mouse folder…", command=self.add).pack(side="left")
            ttk.Button(top, text="Remove selected", command=self.remove).pack(side="left", padx=6)
            ttk.Button(top, text="Build batch files", command=self.run).pack(side="right")
            self.lst = tk.Listbox(self, height=6); self.lst.pack(fill="x", padx=8)
            s = ttk.Frame(self); s.pack(fill="x", padx=8, pady=4)
            self.v = {"aqua": tk.StringVar(value=r"D:\AQuA2"), "sec": tk.StringVar(value="2"),
                      "um": tk.StringVar(value="0.792"), "border": tk.StringVar(value="5"),
                      "opts": tk.StringVar(value=""), "cfu_min": tk.StringVar(value=str(CFU_MIN_EVENTS_DEFAULT)),
                      "cfu_overlap": tk.StringVar(value=str(CFU_OVERLAP_DEFAULT)),
                      "cfu_merge": tk.StringVar(value="0.5"), "cfu_aqua": tk.StringVar(value=""),
                      "overwrite": tk.BooleanVar(value=False)}
            r = 0
            for label, key, w in (("AQuA2 folder", "aqua", 40), ("s per frame (tiff to use)", "sec", 6),
                                  ("µm per pixel", "um", 8), ("border exclusion (px)", "border", 5),
                                  ("default Opt.csv (if a FOV has none)", "opts", 40),
                                  ("CFU: min events per CFU (AQuA2 default 3)", "cfu_min", 5),
                                  ("CFU: overlap threshold (pipeline 0.3, AQuA2 default 0.5)", "cfu_overlap", 5),
                                  ("CFU: post-merge correlation 0..1 (only for an AQuA2 copy of 28 Aug 2026 or later)", "cfu_merge", 5),
                                  ("AQuA2 copy for the CFU step (empty = the AQuA2 folder above; its CFU rules apply)", "cfu_aqua", 40)):
                ttk.Label(s, text=label).grid(row=r, column=0, sticky="w")
                ttk.Entry(s, textvariable=self.v[key], width=w).grid(row=r, column=1, sticky="w", padx=4)
                r += 1
            ttk.Checkbutton(s, text="re-queue tiffs that already have _AQuA2.mat", variable=self.v["overwrite"]).grid(row=r, column=0, columnspan=2, sticky="w")
            self.log = tk.Text(self, height=18, state="disabled"); self.log.pack(fill="both", expand=True, padx=8, pady=6)
            self.after(150, self.poll)

        def add(self):
            d = filedialog.askdirectory(title="Mouse folder (contains the <mouse>_<date>_<run> folders)")
            if d and Path(d) not in self.folders:
                self.folders.append(Path(d)); self.lst.insert("end", d)

        def remove(self):
            for i in reversed(self.lst.curselection()):
                self.lst.delete(i); self.folders.pop(i)

        def run(self):
            v = self.v
            kw = dict(aqua_dir=v["aqua"].get().strip(), sec=float(v["sec"].get() or 2),
                      um_per_px=float(v["um"].get()) if v["um"].get().strip() else None,
                      border=int(v["border"].get()) if v["border"].get().strip() else None,
                      opts_default=Path(v["opts"].get()) if v["opts"].get().strip() else None,
                      cfu_min_events=int(v["cfu_min"].get() or CFU_MIN_EVENTS_DEFAULT), overwrite=bool(v["overwrite"].get()),
                      cfu_overlap=float(v["cfu_overlap"].get() or CFU_OVERLAP_DEFAULT),
                      cfu_merge=float(v["cfu_merge"].get() or 0.5), cfu_aqua_dir=v["cfu_aqua"].get().strip() or None,
                      log=lambda s: self.q.put(s + "\n"))
            threading.Thread(target=self.worker, args=(list(self.folders), kw), daemon=True).start()

        def worker(self, folders, kw):
            for f in folders:
                try:
                    build_mouse(f, **kw)
                except Exception as e:
                    self.q.put(f"ERROR {f}: {e}\n")
            self.q.put("\nDone.\n")

        def poll(self):
            try:
                while True:
                    s = self.q.get_nowait()
                    self.log.configure(state="normal"); self.log.insert("end", s); self.log.see("end")
                    self.log.configure(state="disabled")
            except queue.Empty:
                pass
            self.after(150, self.poll)

    App().mainloop()


