                    border=a.border, paradigm=a.paradigm, n_fov=a.n_fov, stim_after_run=a.stim_after_run,
                    cfu_min_events=a.cfu_min_events, cfu_overlap=a.cfu_overlap,
                    cfu_aqua_dir=a.cfu_aqua, cfu_merge=a.cfu_merge, cfu_redo=a.cfu_redo,
