FOV_RE = re.compile(r"fov[_\- ]?0*(\d+)", re.I)
DATE_RE = re.compile(r"(?<!\d)(\d{6})(?!\d)")


def find_opt_file(mouse_dir: Path, exp, run_folders: list[Path], fallback: Path | None,
                  log=print):
    r"""The AQuA2 settings file (GUI SaveOpts) that belongs to this FOV experiment.

    Looked for, in order:
      1. <mouse>\<experiment>_Opt.csv or <mouse>\aqua_opts\<experiment>_Opt.csv
      2. any *_Opt.csv in <mouse>\ or <mouse>\aqua_opts\ whose name contains
         FOV<k> for this experiment's FOV — this is the normal case: save one
         file per FOV in the animal folder (FOV1_Opt.csv, or the GUI's suggested
         name with FOV1 in it) and it is used for that FOV on every day
      3. any *_Opt.csv in <mouse>\ whose name contains one of this
         experiment's run names (the GUI's default name identifies the run)
      4. any *_Opt.csv inside the experiment's own run folders (earliest first)
      5. --opts <file>
    """
    roots = [mouse_dir, mouse_dir / "aqua_opts"]
    for r in roots:
        for c in (r / f"{exp.name}_Opt.csv", r / f"FOV{exp.fov}_Opt.csv"):
            if c.exists():
                return c, f"{c.parent.name}\\{c.name}"
    pool = []
    for r in roots:
        if r.is_dir():
            pool += sorted(r.glob("*_Opt.csv"))
    hits = [p for p in pool if any(int(m) == exp.fov for m in FOV_RE.findall(p.stem))]
    if hits:
        # with several FOV<k> files, prefer one that names a day of this
        # experiment, then one with no day in its name, then any other day
        exp_dates = {d for n, _ in exp.runs for d in DATE_RE.findall(Path(n).stem)}

        def score(p):
            ds = set(DATE_RE.findall(p.stem))
            return 2 if ds & exp_dates else (1 if not ds else 0)

        hits.sort(key=lambda p: (-score(p), p.name))
        if len(hits) > 1:
            log(f"  note: {len(hits)} settings files name FOV{exp.fov} — using {hits[0].name}")
        if score(hits[0]) == 0:
            other = ", ".join(sorted(set(DATE_RE.findall(hits[0].stem))))
            log(f"  note: {hits[0].name} was saved for day {other}; applying it to "
                f"{'/'.join(sorted(exp_dates))} too (which is the point of tuning on the first day)")
        return hits[0], f"FOV{exp.fov} in the file name"
    run_stems = {Path(n).stem for n, _ in exp.runs}
    hits = [p for p in pool if any(stem in p.stem for stem in run_stems)]
    if hits:
        return hits[0], f"names a run of this experiment ({hits[0].name})"
    for rf in run_folders:
        found = sorted(rf.glob("*_Opt.csv"))
        if found:
            if len(found) > 1:
                log(f"  note: {rf.name} has {len(found)} *_Opt.csv files — using {found[0].name}")
            return found[0], f"run folder {rf.name}"
    if fallback and Path(fallback).exists():
        return Path(fallback), "--opts default"
    shipped = Path(__file__).resolve().parent / "default_Opt.csv"
    if shipped.exists():
        # last resort: the settings shipped with the pipeline, so that a new animal can be queued (and
        # tuned in tab 3, which then writes aqua_opts\<experiment>_Opt.csv — found by rule 1 next time)
        return shipped, "shipped default_Opt.csv — no settings file of its own; tune it in tab 3"
    return None, None


def condition_opt_file(mouse_dir: Path, exp_name: str, condition: str) -> Path | None:
    """A settings file for ONE condition of an experiment (aqua_tune --apply with the matched-sensitivity rule
    writes aqua_opts\\<experiment>_<condition>_Opt.csv when pre and post need different settings to detect with
    the same measured sensitivity); None when the experiment's own file is to be used for every run."""
    if not condition:
        return None
    for r in (Path(mouse_dir) / "aqua_opts", Path(mouse_dir)):
        c = r / f"{exp_name}_{condition}_Opt.csv"
        if c.exists():
            return c
    return None


def build_preset(opt_values: dict, sec_per_frame: float, um_per_px: float | None,
                 border: int | None, log=print, warn: bool = True) -> dict:
    """Template rows filled from an Opt file; returns {variable: value-string}."""
    vals = {}
    for name, var, typ, default in OPT_TEMPLATE_ROWS:
        if not var:
            continue
        vals[var] = opt_values.get(var, default) if opt_values.get(var, "") != "" else default
    # values that must come from the data / the CLI
    fr = vals.get("frameRate")
    try:
        if warn and abs(float(fr) - sec_per_frame) > 1e-3:
            log(f"  note: Opt file says {fr} s/frame, tiff json says {sec_per_frame:.4f} — using the tiff value")
    except ValueError:
        pass
    vals["frameRate"] = f"{sec_per_frame:.6g}"
    if um_per_px is not None:
        vals["spatialRes"] = f"{um_per_px:.6g}"
    if border is not None:
        vals["regMaskGap"] = str(int(border))
    return vals


def _as_seen(path, mouse_dir: Path, as_root: str | None) -> str:
    """The path as the machine that will run MATLAB sees it: with --as-root the
    mouse folder is written as that root (Windows separators when it looks
    like a Windows path), otherwise the path as it is here."""
    path = Path(path)
    if not as_root:
        return str(path)
    try:
        rel = path.relative_to(mouse_dir)
    except ValueError:
        return str(path)
    win = ":" in as_root[:3] or "\\" in as_root
    sep = "\\" if win else "/"
    root = as_root.rstrip("\\/")
    return root + ("" if rel == Path(".") else sep + sep.join(rel.parts))


CFU_OVERLAP_DEFAULT = 0.3   # the pipeline's overlap threshold (AQuA2's own default is 0.5) — see GUIDE.md "CFU rules"
CFU_MIN_EVENTS_DEFAULT = 1  # every event forms a unit (AQuA2's own default is 3)


def cfu_aqua_folder(mouse_dir: Path, aqua_dir: str, cfu_aqua_dir: str | None = None, log=print) -> str:
    """The AQuA2 copy the CFU batch runs with: the one given explicitly, else
    the copy that detects the events (the GUI's top row). A copy from 28 Aug
    2026 on brings AQuA2's newer CFU rules (basin splitting + post-merge), which
    the pipeline does not use unless such a copy is named here on purpose."""
    given = (cfu_aqua_dir or "").strip().strip('"')
    if given:
        log(f"CFU step: AQuA2 copy {given} (named explicitly; ITS CFU rules apply — see GUIDE.md 'CFU rules')")
        return given
    return aqua_dir


def cfu_merge_correlation(control: float) -> float:
    """AQuA2's 'Post-merge correlation' control (0..1) -> the minimum curve
    correlation of its duplicate-unit merge (0.85 .. 1.0; 0.5 = 0.925 = default)."""
    c = min(max(float(control), 0.0), 1.0)
    return round(0.85 + 0.15 * c, 4)


def build_mouse(mouse_dir: Path, aqua_dir: str, opts_default: Path | None = None,
                sec: float | None = 2.0, um_per_px: float | None = None, border: int | None = None,
                paradigm: str = "auto", n_fov: int | None = None, stim_after_run: int | None = None,
                cfu_min_events: int = CFU_MIN_EVENTS_DEFAULT, cfu_overlap: float = CFU_OVERLAP_DEFAULT,
                overwrite: bool = False,
                tol: float = 0.25, only_fov: list[int] | None = None, as_root: str | None = None,
                cfu_aqua_dir: str | None = None, cfu_merge: float = 0.5, cfu_redo: bool = False,
                log=print, stats: dict | None = None) -> Path | None:
    """Writes <mouse>\\aqua_batch\\ and returns it (None when no runs). A run is
    queued when it has no _AQuA2.mat, when overwrite is on, or when its FOV's
    settings file is newer than its result (settings changed — e.g. written by
    aqua_tune --apply — so the result is stale; the shipped default_Opt.csv
    is exempt, its date means nothing). `stats`, if given, receives
    {queued, done, stale, no_settings, experiments}.
    v41: the CFU batch applies AQuA2's published CFU rule with `cfu_overlap`
    (pipeline default 0.3, AQuA2's 0.5) and `cfu_min_events`; it redoes a
    result's CFU file when the CFU rules changed, or every one with `cfu_redo`.
    `cfu_aqua_dir` names another AQuA2 copy for the CFU step (its rules then
    apply; `cfu_merge` is that copy's post-merge control, 0..1)."""
    mouse_dir = Path(mouse_dir)
    seen = lambda p: _as_seen(p, mouse_dir, as_root)     # noqa: E731
    stats = stats if stats is not None else {}
    stats.update({"queued": 0, "done": 0, "stale": 0, "no_settings": 0, "experiments": 0})
    exps = plan_mouse(mouse_dir, paradigm=paradigm, n_fov=n_fov, stim_after_run=stim_after_run)
    if not exps:
        log(f"{mouse_dir}: no runs found"); return None
    log(describe(exps))
    cfu_dir = cfu_aqua_folder(mouse_dir, aqua_dir, cfu_aqua_dir, log=log)
    presets: list[dict] = []          # unique parameter sets
    preset_src: list[str] = []
    rows = []                         # batch.csv rows
    manifest = {"mouse": mouse_dir.name, "aqua_dir": aqua_dir, "cfu_aqua_dir": cfu_dir,
                "cfu": {"min_events": int(cfu_min_events), "overlap": float(cfu_overlap),
                        "rule": "AQuA2 published overlap clustering (single linkage on the weighted footprint overlap); "
                                "post_merge / min_curve_correlation only apply to an AQuA2 copy of 28 Aug 2026 or later named as cfu_aqua_dir",
                        "post_merge": float(cfu_merge), "min_curve_correlation": cfu_merge_correlation(cfu_merge),
                        "redo_all": bool(cfu_redo)},
                "experiments": []}
    n_skip = 0
    n_stale = 0
    shipped_default = Path(__file__).resolve().parent / "default_Opt.csv"
    if only_fov:
        log(f"only FOV {', '.join(str(f) for f in only_fov)} — other FOVs are left out of batch.csv")
    for e in exps:
        if only_fov and e.fov not in only_fov:
            continue
        run_folders = []
        for sbx_name, cond in e.runs:
            hits = list(mouse_dir.rglob(sbx_name))
            if hits:
                run_folders.append(hits[0].parent)
        opt_path, src = find_opt_file(mouse_dir, e, run_folders, opts_default, log=log)
        if opt_path is None:
            log(f"\n{e.name}: NO settings file — tune this FOV in the AQuA2 GUI, then SaveOpts into "
                + " or ".join(r.name for r in run_folders)
                + f", or save it as aqua_opts\\{e.name}_Opt.csv (or aqua_opts\\FOV{e.fov}_Opt.csv)")
            manifest["experiments"].append({"name": e.name, "fov": e.fov, "paradigm": e.paradigm,
                                            "opt_file": None, "runs": []})
            stats["no_settings"] += 1
            continue
        opt_values = read_opt_csv(opt_path)
        log(f"\n{e.name}: settings from {opt_path.name} ({src})")
        ex_entry = {"name": e.name, "fov": e.fov, "paradigm": e.paradigm, "opt_file": seen(opt_path), "runs": []}
        stats["experiments"] += 1
        try:
            opt_mtime = 0.0 if opt_path.resolve() == shipped_default.resolve() else opt_path.stat().st_mtime
        except OSError:
            opt_mtime = 0.0
        warned = False
        cond_opts: dict = {}                     # condition -> (opt_path, values, mtime): aqua_tune's matched-sensitivity
        for (sbx_name, cond), rf in zip(e.runs, run_folders):   # settings (v36), one file per condition of the day
            tif = pick_binned_tif(rf, sec, tol=tol, log=log)
            if tif is None:
                log(f"  {rf.name}: no binned tiff — run unpack_bin.py first")
                continue
            files = aqua_files(tif)
            spf = None
            if files["json"].exists():
                try:
                    spf = float(json.loads(files["json"].read_text()).get("seconds_per_frame"))
                except Exception:
                    spf = None
            if spf is None:
                spf = sec or float(opt_values.get("frameRate", 2.0))
                log(f"  {tif.name}: no .json sidecar — assuming {spf} s/frame")
            run_opt, run_values, run_mtime = opt_path, opt_values, opt_mtime
            if cond not in cond_opts:
                cpath = condition_opt_file(mouse_dir, e.name, cond)
                if cpath is not None:
                    try:
                        cond_opts[cond] = (cpath, read_opt_csv(cpath), cpath.stat().st_mtime)
                        log(f"  [{cond}] settings of this condition: {cpath.parent.name}\\{cpath.name} (matched-sensitivity tuning)")
                    except Exception as ex:
                        log(f"  [{cond}] {cpath.name} not readable ({ex}) — the experiment's settings are used")
                        cond_opts[cond] = None
                else:
                    cond_opts[cond] = None
            if cond_opts.get(cond):
                run_opt, run_values, run_mtime = cond_opts[cond]
            vals = build_preset(run_values, spf, um_per_px, border, log, warn=not warned)
            warned = True
            if vals in presets:
                pidx = presets.index(vals) + 1
            else:
                presets.append(vals); preset_src.append(f"{e.name} [{cond}] <- {run_opt.name}")
                pidx = len(presets)
            done = files["res"].exists()
            stale = False
            if done and not overwrite and run_mtime:
                try:
                    stale = files["res"].stat().st_mtime + 1 < run_mtime
                except OSError:
                    stale = False
            if done and not overwrite and not stale:
                n_skip += 1
            else:
                rows.append((seen(tif), pidx))
                if stale:
                    n_stale += 1
            ex_entry["runs"].append({"run": tif.stem, "condition": cond, "tif": seen(tif),
                                     "preset": pidx, "seconds_per_frame": spf, "opt_file": seen(run_opt),
                                     "aqua_done": done, "queued": not (done and not overwrite and not stale)})
            log(f"  {'done ' if done and not stale and not overwrite else 'queue'} [{cond:>7}] {tif.name}  (Preset{pidx})"
                + ("  — settings file newer than the result: analysed again" if stale else ""))
        manifest["experiments"].append(ex_entry)

    out = mouse_dir / "aqua_batch"
    out.mkdir(exist_ok=True)
    # parameters_for_batch.csv
    lines = ["Name,Variable,Type," + ",".join(f"Preset{i + 1}" for i in range(max(1, len(presets))))]
    for name, var, typ, default in OPT_TEMPLATE_ROWS:
        if not var:
            lines.append("," * (2 + max(1, len(presets))))
            continue
        vals = [p.get(var, default) for p in presets] or [default]
        lines.append(",".join([f'"{name}"' if "," in name else name, var, typ] + vals))
    # (a csv left open in Excel or by a stuck reader is locked on Windows: the file is then written under the
    # next free name and the MATLAB scripts point at that name — v40)
    params_csv = write_text_free(out / "parameters_for_batch.csv", "\n".join(lines) + "\n", log=log)
    # batch.csv (paths absolute; outputPath empty = next to the input)
    blines = ["inputPath,preset,outputPath,cellMaskPath,landmarkMaskPath"]
    for tif, pidx in rows:
        blines.append(f"{tif},{pidx},,,")
    batch_csv = write_text_free(out / "batch.csv", "\n".join(blines) + "\n", log=log)
    aqua_script = write_text_free(out / "run_aqua_batch.m", AQUA_SCRIPT.format(
        aqua_dir=_mat(aqua_dir), batch_csv=_mat(seen(batch_csv)),
        params_csv=_mat(seen(params_csv))), log=log)
    res_list = []
    for e in manifest["experiments"]:
        for r in e.get("runs", []):
            t = r["tif"]
            res_list.append("    '" + _mat(t[:-4] + AQUA_SUFFIX + ".mat") + "'")
    cfu_script = write_text_free(out / "run_cfu_batch.m", CFU_SCRIPT.format(
        cfu_aqua_dir=_mat(cfu_dir), mouse_dir=_mat(seen(mouse_dir)), overlap=cfu_overlap,
        res_list="\n".join(res_list) if res_list else "    % (no runs)",
        min_evt=int(cfu_min_events), merge_ctrl=min(max(float(cfu_merge), 0.0), 1.0),
        min_corr=cfu_merge_correlation(cfu_merge), overwrite="true" if overwrite else "false",
        cfu_redo="true" if cfu_redo else "false"), log=log)
    both_script = write_text_free(out / "run_aqua_and_cfu.m", BOTH_SCRIPT.format(
        aqua_script=_mat(seen(aqua_script)), cfu_script=_mat(seen(cfu_script))), log=log)
    manifest["presets"] = [{"preset": i + 1, "source": s, "values": p}
                           for i, (s, p) in enumerate(zip(preset_src, presets))]
    manifest["built"] = time.time()
    # the names actually written (= the canonical ones unless a file was locked); the GUI and batch_done read these
    manifest["files"] = {"batch_csv": batch_csv.name, "params_csv": params_csv.name, "aqua_script": aqua_script.name,
                         "cfu_script": cfu_script.name, "both_script": both_script.name}
    manifest["batch_csv"] = str(batch_csv.name)
    manifest["params_csv"] = str(params_csv.name)
    if only_fov and (out / "manifest.json").exists():
        # a partial run must not make the other FOVs disappear from the manifest
        # (aqua_analyze / cfu_curate read it): merge into the existing one
        try:
            old = json.loads((out / "manifest.json").read_text())
            done_names = {e["name"] for e in manifest["experiments"]}
            manifest["experiments"] = ([e for e in old.get("experiments", []) if e["name"] not in done_names]
                                       + manifest["experiments"])
            manifest["experiments"].sort(key=lambda e: e["name"])
        except Exception:
            pass
    try:
        write_text_free(out / "manifest.json", json.dumps(manifest, indent=2), log=log, allow_alt=False)
    except PermissionError as e:
        raise RuntimeError(str(e)) from e
    stats.update({"queued": len(rows), "done": n_skip, "stale": n_stale})
    log(f"\n{mouse_dir.name}: {len(rows)} tiff(s) queued" + (f" ({n_stale} because their settings file is newer than the result)" if n_stale else "")
        + f", {n_skip} already analysed, {len(presets)} preset(s) -> {out}")
    if not rows and not n_skip:
        log("NOTHING QUEUED: no experiment has a settings file and no default was given — pass --opts default_Opt.csv "
            "(tab 4: 'settings for a FOV that has no *_Opt.csv') and build again; the MATLAB scripts would do nothing")
    elif not rows:
        log("nothing new to run in MATLAB (every tiff has a result; tick 're-queue' / --overwrite to redo them)\n"
            f"  run('{seen(cfu_script)}')      (CFUs, if not built yet)\n"
            f"then: python aqua_analyze.py \"{seen(mouse_dir)}\"")
    else:
        log("Next, in MATLAB (one paste):\n"
            f"  run('{seen(both_script)}')\n"
            f"  (= run('{seen(aqua_script)}') then run('{seen(cfu_script)}'))\n"
            f"then: python aqua_analyze.py \"{seen(mouse_dir)}\"")
    return out


def batch_done(mouse_dir: Path) -> dict:
    """What the MATLAB scripts of the batch have produced so far: every tiff of
    batch.csv needs an _AQuA2.mat newer than the batch build, every result of
    the manifest a _res_cfu.mat and an _AQuA2_events.csv newer than its .mat.
    Returns {done, n_queued, aqua_done, n_results, cfu_done, pending_aqua, pending_cfu, text}."""
    mouse_dir = Path(mouse_dir)
    out = mouse_dir / "aqua_batch"
    man = {}
    try:
        man = json.loads((out / "manifest.json").read_text())
    except Exception:
        return {"done": False, "text": "no aqua_batch\\manifest.json — build the batch first", "n_queued": 0, "aqua_done": 0,
                "n_results": 0, "cfu_done": 0, "pending_aqua": [], "pending_cfu": []}
    built = float(man.get("built") or (out / "manifest.json").stat().st_mtime)
    queued = []
    try:
        for ln in (out / man.get("batch_csv", "batch.csv")).read_text().splitlines()[1:]:
            if ln.strip():
                queued.append(relocate(ln.split(",")[0], mouse_dir))
    except Exception:
        pass

    def result_time(tif: Path):
        """Newest of the AQuA2 result files (.mat; the feature table when the .mat is gone), or None."""
        f = aqua_files(tif)
        ts = [p.stat().st_mtime for p in (f["res"], f["features"]) if p.exists()]
        return max(ts) if ts else None
    pending_aqua = []
    for tif in queued:
        t = result_time(tif)
        if t is None or t + 1 < built:
            pending_aqua.append(re.split(r"[\\/]+", str(tif))[-1].replace(".tif", ""))
    pending_cfu, n_results = [], 0
    for e in man.get("experiments", []):
        for r in e.get("runs", []):
            tif = Path(relocate(r["tif"], mouse_dir))
            t_res = result_time(tif)
            if t_res is None:
                continue                                        # counted under pending_aqua when queued
            n_results += 1
            f = aqua_files(tif)
            ev_csv = Path(str(tif.with_suffix("")) + AQUA_SUFFIX + "_events.csv")
            if not (f["cfu"].exists() and ev_csv.exists() and f["cfu"].stat().st_mtime + 1 >= t_res and ev_csv.stat().st_mtime + 1 >= t_res):
                pending_cfu.append(tif.stem)
    done = not pending_aqua and not pending_cfu and (n_results > 0 or not queued)
    text = (f"AQuA2: {len(queued) - len(pending_aqua)} of {len(queued)} queued tiff(s) have a result; "
            f"CFU + export: {n_results - len(pending_cfu)} of {n_results} result(s) done"
            + ("" if done else f"; waiting for {', '.join((pending_aqua + pending_cfu)[:4])}"
               + (" …" if len(pending_aqua) + len(pending_cfu) > 4 else "")))
    return {"done": done, "n_queued": len(queued), "aqua_done": len(queued) - len(pending_aqua), "n_results": n_results,
            "cfu_done": n_results - len(pending_cfu), "pending_aqua": pending_aqua, "pending_cfu": pending_cfu, "text": text}


